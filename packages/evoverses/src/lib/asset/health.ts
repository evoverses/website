export function levelHealth(baseHealth: number, level: number, training = 0): number {
  const end = baseHealth + Math.floor(training / 5), start = Math.max(1, Math.round(end / 10));
  return Math.round((start * (100 - level) + end * (level - 1)) / 99);
}

export function currentLevelHealth(species: string, xp: number): number | undefined {
  const entry = speciesHealth[species.toLowerCase()];
  if (!entry || !Number.isSafeInteger(xp) || xp < 0) return undefined;
  let level = 1;
  for (let next = 2; next <= 100; next++) {
    if (xp < Math.round((next ** 3 * entry.maxXp) / 1000000)) break;
    level = next;
  }
  return levelHealth(entry.health, level);
}
